import { createCommandRecord } from "../lib/commandContract.js";

const fact = (name) => ({ fact: name, value: true, source: "operator-confirmed" });

const noCleanup = (note = "No persistent state change is expected from this validation step.") => ({
  required: false,
  command: "",
  note,
});

const stopWithCtrlC = (owner) => ({
  required: true,
  command: `Press Ctrl-C in the terminal that owns ${owner}.`,
  note: `Stop only ${owner}; preserve its captured output before closing the terminal.`,
});

const cleaned = (note) => ({ required: false, command: "", note });

const defaults = {
  policy: "exam-core",
  risk: "low",
  stateChange: "none",
  executionEnabled: true,
  prerequisites: [
    "Select exactly one in-scope machine and confirm that a pivot is required.",
    "Confirm the host named by RUN ON and review the exact command before running it.",
  ],
  expectedPositiveSignal: "The operator-reviewed output matches the stated validation signal for this one step.",
  expectedNegativeSignal: "The expected signal is absent, or an explicit error shows that the prerequisite, direction, route, or tool assumption is wrong.",
  positiveBranch: "Save the output, confirm this step manually, then select the next numbered step in the same playbook.",
  negativeBranch: "Save the error, mark this step failed or blocked, correct only the failed prerequisite, and do not skip ahead.",
  evidence: ["Exact rendered command", "Timestamp and RUN ON host", "Relevant raw output", "Operator result state"],
  sideEffects: "Creates only normal validation traffic unless the state-change field says otherwise.",
  verificationCommand: "Review the command output and target context manually.",
  cleanup: noCleanup(),
  fallback: "Re-check route ownership, callback direction, listener address, tool version, and the selected host before choosing a documented fallback playbook.",
};

function pivotStep({
  id,
  title,
  command,
  purpose,
  runsOn,
  facts = [],
  prerequisites,
  ...metadata
}) {
  const raw = {
    ...defaults,
    id: `pivot.${id}`,
    key: `pivot-${id}`,
    title,
    label: title,
    value: command,
    purpose,
    runsOn,
    applicability: {
      mode: "all",
      predicates: [fact("target.selected-and-in-scope"), ...facts.map(fact)],
    },
    prerequisites: prerequisites || defaults.prerequisites,
    ...metadata,
  };
  return Object.freeze(createCommandRecord({ id: "pivot-playbooks", title: "Manual pivot playbooks" }, raw));
}

